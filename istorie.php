            <h2>Istoria BMW</h2>
            <h4>Înainte de al Doilea Război Mondial</h4>
            <p class="fade-text">
                Compania își are istoria încă din 1913, când Karl Friedrich Rapp a fondat o întreprindere pentru producția de motoare de avioane. 
                Firma Bayerische Motoren Werke, creată pe baza întreprinderii, a fost înregistrată oficial în 1917. 
                După Primul Război Mondial, Tratatul de la Versailles din 1919 a interzis producția de avioane în Germania, 
                forțând BMW să treacă la producția de mașini agricole, bunuri de uz casnic și frâne de tren. 
                În 1923, prima motocicletă BMW a fost produsă la fabrica din München.
            </p>
            <p class="fade-text">
                În 1924, primul zbor intercontinental către Persia a avut loc cu o aeronavă echipată cu motoare BMW. 
                În 1926, hidroavionul Rohrbach Ro VII cu motoare BMW VI a stabilit cinci recorduri mondiale. 
                În 1927, au fost stabilite 87 de recorduri mondiale ale aviației, 29 dintre ele pe aeronave cu motoare BMW. 
                În 1928, BMW a achiziționat o fabrică de mașini în Eisenach (Turingia), iar în anul următor, prima mașină a companiei, Dixi, a fost produsă la această fabrică.
            </p>
            <p class="fade-text">
                În același an, Ernst Henne, pe o motocicletă cu motor BMW, devine cel mai rapid motociclist din lume. 
                În 1933, compania a început să producă motoare de avioane pentru Luftwaffe, 
                în special dobândind o licență pentru a produce motoare Hornet. 
                A început și producția mașinilor din seria 300, în special BMW-ul de mare succes 328, introdus în septembrie 1936.
            </p>
            <p class="fade-text">
                În iunie 1939, Siemens și-a vândut filiala de inginerie mecanică către BMW, care includea Brandenburg Motor Works, 
                precum și fabricile, laboratoarele și locurile de testare din Spandau, Niederbarnim, Basdorf și Sühlsdorf. 
                În plus, a fost construită o nouă fabrică lângă München, cu fonduri guvernamentale. 
                Pe baza întreprinderilor achiziționate, au fost create o fabrică de motoare de avioane și rachete 
                (Flugzeugturbinenfabrik) și o divizie de tehnologie de rachete și arme de rachetă (BMW-Raketenabteilung) cu un centru de cercetare în Sühlsdorf 
                și producție în Spandau.
            </p>
            <p class="fade-text">
                Până în toamna anului 1940, fabricile de rachete BMW din Spandau și Niederbarnim au angajat aproximativ 10.000 de cetățeni germani 
                plus prizonieri de război, cărora li s-au alăturat curând Ostarbeiters. 
                În 1942, sub presiunea Biroului de Armament al Reichului, Fritz Hille a preluat funcția de președinte al Consiliului.
            </p>
            
